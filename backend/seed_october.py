def main() -> None:
    engine = build_engine(f"sqlite:///{Path(__file__).resolve().parents[1] / 'afisha.sqlite3'}")
    Base.metadata.create_all(engine)
    session_factory = build_session_factory(engine)

    added = 0
    skipped = 0
    with session_factory() as session:
        existing = {s for s in session.scalars(select(Event.slug)).all()}
        for slug, (title, category, d, t, venue, price) in OCTOBER_EVENTS.items():
            if slug in existing:
                skipped += 1
                continue
            session.add(Event(
                title=title, slug=slug, status="published", category=category,
                date=d, time=t, venue=venue, price=price,
            ))
            added += 1
        session.commit()
    print(f"Добавлено событий: {added}, пропущено (уже есть): {skipped}")


if __name__ == "__main__":
    main()